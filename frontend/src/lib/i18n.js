const I18nCtx = createContext({ lang: "en", t: (k) => k, setLang: () => {} });

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("obi_lang") || "en");
  const change = (l) => { setLang(l); localStorage.setItem("obi_lang", l); };
  const t = (k) => (dict[lang] && dict[lang][k]) || dict.en[k] || k;
  return (
    <I18nCtx.Provider value={{ lang, t, setLang: change }}>
      {children}
    </I18nCtx.Provider>
  );
}

export const useI18n = () => useContext(I18nCtx);
